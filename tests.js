const L = require("./logic.js");
const assert = require("assert");
const now = new Date(2026, 9, 16, 12, 0, 0).getTime();
const H = 3600000, D = 86400000;
assert.strictEqual(L.countdown(now + 30 * 60000, now), "in 30 min");
assert.strictEqual(L.countdown(now + 5 * H + 20 * 60000, now), "in 5h 20m");
assert.strictEqual(L.countdown(now + 2 * D + 3 * H, now), "in 2d 3h");
assert.strictEqual(L.countdown(now + 5 * D, now), "in 5d");
assert.strictEqual(L.countdown(now - 2 * H, now), "2h overdue");
assert.strictEqual(L.countdown(now + 10000, now), "due now");
const it = (due, done) => ({ id: "x" + due, title: "t", due, prio: 1, done: !!done });
assert.strictEqual(L.bucket(it(now - 1), now), "overdue");
assert.strictEqual(L.bucket(it(now + H), now), "today");
assert.strictEqual(L.bucket(it(now + 2 * D), now), "week");
assert.strictEqual(L.bucket(it(now + 20 * D), now), "later");
assert.strictEqual(L.bucket(it(now + H, true), now), "done");
const list = [it(now + 3 * D), it(now + H), it(now - D)];
assert.strictEqual(L.nextUp(list, now).due, now + H);
assert.strictEqual(L.nextUp([it(now - D)], now).due, now - D);
assert.strictEqual(L.nextUp([], now), null);
assert.strictEqual(L.validate({ items: [{ title: "a", due: 5 }, { title: "", due: 1 }, { due: 3 }, null] }).length, 1);
assert.strictEqual(L.validate(null).length, 0);
console.log("all tests passed");
